export type IconName = keyof typeof DRAWINGS;
export const ICON_NAMES = Object.keys(DRAWINGS) as IconName[];

/** Raw drawing rows; exported for tests and the `/dev/ui` gallery. */
export function iconDrawing(name: IconName): readonly string[] {
  return DRAWINGS[name];
}

export interface IconPaths {
  /** SVG path data for the line layer (horizontal runs merged). */
  line: string;
  /** SVG path data for the dithered fill layer; empty when the icon has none. */
  fill: string;
}

function runsToPath(rows: readonly string[], match: (cell: string, x: number, y: number) => boolean): string {
  const parts: string[] = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (!match(row[x] ?? ".", x, y)) {
        x += 1;
        continue;
      }
      const start = x;
      while (x < row.length && match(row[x] ?? ".", x, y)) x += 1;
      parts.push(`M${start} ${y}h${x - start}v1h${start - x}z`);
    }
  });
  return parts.join("");
}

const pathCache = new Map<IconName, IconPaths>();

/** Compiles an icon into crisp, run-length-merged SVG paths (memoised). */
export function iconPaths(name: IconName): IconPaths {
  const cached = pathCache.get(name);
  if (cached) return cached;
  const rows = DRAWINGS[name];
  const paths: IconPaths = {
    line: runsToPath(rows, (cell) => cell === "#"),
    fill: runsToPath(rows, (cell, x, y) => cell === "+" && bayerLit(x, y, FILL_COVERAGE)),
  };
  pathCache.set(name, paths);
  return paths;
}
