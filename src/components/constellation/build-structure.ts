/**
 * Constellation render layer — simulation state → React render structure.
 *
 * This is the only place that translates the physics engine's
 * `SimulationState` into the declarative tree the canvas renders. It is pure
 * (no DOM, no React, no clocks) so it can be unit-tested in Vitest's `node`
 * environment, and so it can safely run during SSR if Phase C ever
 * server-renders a static constellation.
 *
 * It runs ONCE per data change / resize / track switch — never per frame.
 */

import type {
  MatchInput,
  SelfIdentity,
  SimulationState,
} from "@/lib/constellation-layout";
import type { MatchTrack } from "@/types/microtest-v2";

import {
  GHOST_ANIMAL_ID,
  GHOST_COLOR_ID,
  GHOST_OPACITY,
  MAX_RENDERED_EDGES,
  SPRITE_SIZE_FACTOR,
  buildAdjacency,
  edgeKey,
  edgeStrokeOpacity,
  edgeStrokeWidth,
  matchAriaLabel,
  nodeOpacity,
  selfAriaLabel,
  selectRenderEdges,
} from "./render-helpers";
import { CONSTELLATION_COPY, type ConstellationMatchInput } from "./types";
import type {
  ConstellationSelfInput,
  ConstellationStructure,
  NodeMeta,
  RenderEdge,
  RenderNode,
} from "./types";

/** Neutral thread colour for match↔match links (the ink token from globals.css). */
export const EDGE_NEUTRAL_COLOR = "#17231d";

/** Adapts the view-model self node to the engine's `SelfIdentity`. */
export function toSelfIdentity(me: ConstellationSelfInput): SelfIdentity {
  return { id: me.id, animal: me.animalId, color: me.colorHex, alias: me.alias };
}

/**
 * Adapts the view-model matches to the engine's `MatchInput`.
 *
 * The engine needs the animal ID (it is only used as an opaque label) and a hex
 * for display; the human-readable names stay in `NodeMeta`.
 */
export function toMatchInputs(
  matches: readonly ConstellationMatchInput[],
): MatchInput[] {
  return matches.map((match) => ({
    id: match.id,
    animal: match.animalId,
    color: match.colorHex,
    alias: match.alias,
    similarity: match.similarity,
    track: match.track,
  }));
}

/**
 * Indexes every participant by id, including the self node. Ghosts are filled in
 * lazily by `structureFromState` because their ids are generated by the engine.
 */
export function buildNodeMeta(
  me: ConstellationSelfInput,
  matches: readonly ConstellationMatchInput[],
): Map<string, NodeMeta> {
  const meta = new Map<string, NodeMeta>();
  meta.set(me.id, {
    animalId: me.animalId,
    colorId: me.colorId,
    colorHex: me.colorHex,
    animalName: me.animalName,
    colorName: me.colorName,
    alias: me.alias,
    similarity: 1,
  });
  for (const match of matches) {
    meta.set(match.id, {
      animalId: match.animalId,
      colorId: match.colorId,
      colorHex: match.colorHex,
      animalName: match.animalName,
      colorName: match.colorName,
      alias: match.alias,
      similarity: match.similarity,
    });
  }
  return meta;
}

/** Meta for the decorative stars the engine synthesises. */
export const GHOST_META: NodeMeta = {
  animalId: GHOST_ANIMAL_ID,
  colorId: GHOST_COLOR_ID,
  colorHex: "#c9d4ff",
  animalName: CONSTELLATION_COPY.ghostDecorative,
  colorName: "",
  alias: "",
  similarity: 0,
};

function resolveMeta(meta: Map<string, NodeMeta>, id: string, isGhost: boolean): NodeMeta {
  if (isGhost) return GHOST_META;
  return (
    meta.get(id) ?? {
      animalId: GHOST_ANIMAL_ID,
      colorId: GHOST_COLOR_ID,
      colorHex: "#c9d4ff",
      animalName: "",
      colorName: "",
      alias: "",
      similarity: 0,
    }
  );
}

/**
 * Builds the full render structure from a simulation state.
 *
 * - Node sprite size is `radius * SPRITE_SIZE_FACTOR`; the 12×12 grid carries
 *   ~1 cell of transparent margin, so the visible body ends up about the size
 *   of the collision circle.
 * - Real match brightness and size both scale with similarity (via the engine's
 *   own radius formula and `nodeOpacity`).
 * - Ghosts are dim, decorative and never interactive.
 * - Edges are capped by `selectRenderEdges`; adjacency is built from the CAPPED
 *   list so the highlight always matches what is painted.
 */
export function structureFromState(
  state: SimulationState,
  meta: Map<string, NodeMeta>,
  threshold: number,
  track: MatchTrack,
  maxEdges: number = MAX_RENDERED_EDGES,
): ConstellationStructure {
  const selfNode = state.nodes.find((node) => node.isSelf);
  const selfId = selfNode?.id ?? "";

  const nodes: RenderNode[] = state.nodes.map((node) => {
    const info = resolveMeta(meta, node.id, node.isGhost);
    const ariaLabel = node.isGhost
      ? CONSTELLATION_COPY.ghostDecorative
      : node.isSelf
        ? selfAriaLabel(info.animalName, info.colorName, info.alias)
        : matchAriaLabel(info.animalName, info.colorName, node.similarity, track);
    return {
      id: node.id,
      radius: node.radius,
      displaySize: node.radius * SPRITE_SIZE_FACTOR,
      isSelf: node.isSelf,
      isGhost: node.isGhost,
      animalId: info.animalId,
      colorId: info.colorId,
      colorHex: info.colorHex,
      alias: info.alias,
      ariaLabel,
      opacity: node.isGhost ? GHOST_OPACITY : node.isSelf ? 1 : nodeOpacity(node.similarity, threshold),
      initialX: node.x,
      initialY: node.y,
    };
  });

  const rendered = selectRenderEdges(state.edges, selfId, maxEdges);
  const colorById = new Map<string, string>();
  const positionById = new Map<string, { x: number; y: number }>();
  for (const node of state.nodes) positionById.set(node.id, { x: node.x, y: node.y });
  for (const node of nodes) colorById.set(node.id, node.colorHex);

  const edges: RenderEdge[] = rendered.map((edge) => {
    const touchesSelf = edge.source === selfId || edge.target === selfId;
    const otherId = edge.source === selfId ? edge.target : edge.source;
    const color = touchesSelf
      ? (colorById.get(otherId) ?? EDGE_NEUTRAL_COLOR)
      : EDGE_NEUTRAL_COLOR;
    const source = positionById.get(edge.source);
    const target = positionById.get(edge.target);
    return {
      key: edgeKey(edge.source, edge.target),
      source: edge.source,
      target: edge.target,
      similarity: edge.similarity,
      width: edgeStrokeWidth(edge.similarity),
      opacity: edgeStrokeOpacity(edge.similarity),
      color,
      targetDistance: edge.targetDistance,
      sourceX: source?.x ?? 0,
      sourceY: source?.y ?? 0,
      targetX: target?.x ?? 0,
      targetY: target?.y ?? 0,
    };
  });

  return {
    nodes,
    edges,
    adjacency: buildAdjacency(rendered),
    threshold,
    selfId,
    width: state.width,
    height: state.height,
  };
}
