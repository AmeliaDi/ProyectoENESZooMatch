"""Renders docs/TEST.md and the quiz_items block of supabase/seed.sql."""

from __future__ import annotations

import json
import re
from pathlib import Path

from bank_model import Item

SECONDS_PER_ITEM = 7  # data/literature/layer-criteria.json budget


def _row(n: int, i: Item) -> str:
    pol = "sel." if i.opciones else ("−" if i.key == -1 else "+")
    text = i.texto + (f" ({' · '.join(i.opciones)})" if i.opciones else "")
    return (f"| {n} | {i.id} | {i.capa} | {i.factor}{' / ' + i.faceta if i.faceta else ''} | {text} "
            f"| {pol} | {i.origen} | {', '.join(i.banderas)} |")


HEADER = "| # | id | Capa | Factor / faceta | Texto | Pol. | Origen | Banderas |\n|---|---|---|---|---|---|---|---|"


def write_test_md(path: Path, core: list[Item], optional: list[Item],
                  modules: list[tuple[str, str, str]]) -> None:
    minutes = len(core) * SECONDS_PER_ITEM / 60
    lines = [
        "# Test ZooMatch: banco de ítems",
        "",
        "> Generado por `scripts/psychometrics/bank.py`; **no editar a mano**. Fuente de verdad del",
        "> banco aprobado en `docs/ITEMS_PROPUESTA.md` (ADR-016). Escala Likert 1–5. `−` = inverso (6 − x).",
        "> Banderas: DS deseabilidad social, AMB ambigüedad, SENS sensible (omitible), 1I escala de un ítem.",
        "",
        f"Núcleo: **{len(core)} ítems** ({len(core) - 3} Likert + 3 filtros), ≈ {minutes:.1f} min a "
        f"{SECONDS_PER_ITEM} s/ítem. Módulos opcionales: **{len(optional)} ítems**.",
        "",
        "## Núcleo (orden de presentación)",
        "",
        HEADER,
        *(_row(n, i) for n, i in enumerate(core, 1)),
        "",
    ]
    for mid, title, desc in modules[1:]:
        block = [i for i in optional if i.modulo == mid]
        lines += [f"## Módulo `{mid}`: {title} ({len(block)} ítems)", "", desc, "", HEADER,
                  *(_row(n, i) for n, i in enumerate(block, 1)), ""]
    lines += [
        "## Límites",
        "",
        "- Traducciones IPIP propias, sin validación en español; la fiabilidad real requiere un piloto.",
        "- MBTI y Eneagrama con 1 ítem por eje/tipo en el núcleo son poco fiables por construcción:",
        "  pesan ≈ 0 en el puntaje y su incertidumbre se muestra.",
        "- Ningún ítem infiere orientación ni identidad: solo se usa lo declarado en FIL1–FIL3.",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def _sql(value: object) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (list, dict)):
        value = json.dumps(value, ensure_ascii=False, separators=(",", ":"))
    return "'" + str(value).replace("'", "''") + "'"


def write_seed(path: Path, items: list[dict[str, object]]) -> None:
    sql = path.read_text(encoding="utf-8")
    rows = ",\n".join(
        "  (" + ", ".join(_sql(v) for v in [
            it["id"], it["categoria"], it["subcategoria"], it["texto"], it["tipo_respuesta"],
            it.get("opciones"), it["polaridad"], it["pesos"], it["track_romance"], it["track_amistad"],
            it["filtro_duro"], it.get("campo_perfil"), it["fuente_id"]]) + ")"
        for it in items)
    block = (
        f"-- ─── 3. Seed Quiz Items ({len(items)} entries, generated by scripts/psychometrics/bank.py) ───\n\n"
        "INSERT INTO public.quiz_items (id, categoria, subcategoria, prompt, tipo_respuesta, opciones, polarity, "
        "weights, track_romance, track_amistad, filtro_duro, campo_perfil, source_id) VALUES\n"
        f"{rows}\nON CONFLICT (id) DO UPDATE SET\n"
    )
    sql, n = re.subn(r"-- ─── 3\. Seed Quiz Items.*?\nON CONFLICT \(id\) DO UPDATE SET\n", lambda _: block,
                     sql, count=1, flags=re.S)
    assert n == 1, "seed.sql quiz_items block not found"
    sql = re.sub(r"--   \d+ quiz items inserted/updated", f"--   {len(items)} quiz items inserted/updated", sql)
    sql = re.sub(r"--   Quiz Items:\s+data/microtest\.json \(\d+ items\)",
                 f"--   Quiz Items:       data/microtest.json ({len(items)} items)", sql)
    path.write_text(sql, encoding="utf-8")
